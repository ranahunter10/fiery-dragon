"""Generate docs/CODEMAP.md: one line per source file (its job, from the file's first
comment or docstring) and its public names, so a session reads one map instead of
re-reading files. Our own idea after Graphify (Graphify-Labs/Graphify), without its
tool: plain text, regenerated by `make codemap`, checked current by CI (`--check`).

    python3 tools/codemap.py            write docs/CODEMAP.md
    python3 tools/codemap.py --check    exit 1 if docs/CODEMAP.md is stale
"""
from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "CODEMAP.md"
SKIP = ("third_party/", "bpf/vmlinux/", "docs/", "schema/generated/")
EXTS = (".c", ".h", ".py", ".sh", ".toml")

C_FUNC = re.compile(r"^(?!static\b)(?:[A-Za-z_][\w\s\*]*?)\b([a-z_][a-z0-9_]*)\s*\([^;]*\)\s*$")
C_PROTO = re.compile(r"^(?!static\b|#|typedef\b)[A-Za-z_][\w\s\*]*?\b([a-z_][a-z0-9_]*)\s*\([^)]*\)?[^;]*;")
BPF_PROG = re.compile(r"^SEC\(\"([^\"]+)\"\)")
PY_DEF = re.compile(r"^(?:def|class)\s+([A-Za-z_]\w*)")
SH_FUNC = re.compile(r"^([a-z_][a-z0-9_]*)\s*\(\)\s*\{")


def files() -> list[str]:
    out = subprocess.run(["git", "ls-files"], cwd=ROOT, capture_output=True, text=True, check=True).stdout
    return sorted(f for f in out.split() if f.endswith(EXTS) and not f.startswith(SKIP))


def job(text: str, path: str) -> str:
    """The first sentence of the file's leading comment or docstring."""
    lines = text.splitlines()
    body: list[str] = []
    for ln in lines[:40]:
        s = ln.strip()
        if not s or "SPDX-License" in s or s.startswith("#!") or s.startswith("#include"):
            if body:
                break
            continue
        if path.endswith((".py",)) and (s.startswith('"""') or body):
            s = s.strip('"').strip()
            if s:
                body.append(s)
            if body and ln.rstrip().endswith('"""') and len(body) >= 1 and not ln.strip() == '"""':
                break
            continue
        hash_comment = path.endswith((".py", ".sh", ".toml")) and s.startswith("#")
        if s.startswith("#") and not hash_comment:
            continue                      # C preprocessor line
        if s.startswith(("/*", "*", "//")) or hash_comment:
            s = s.lstrip("/*# ").rstrip("*/ ").strip()
            if s:
                body.append(s)
            continue
        break
    first = re.sub(r"\s+", " ", " ".join(body))
    # drop a leading "name:" label (e.g. "spine.bpf.c:" or "p6-racer:"), then take the first sentence
    first = re.sub(r"^[\w.\-/ ]{1,40}:\s+", "", first, count=1) if re.match(r"^[\w.\-/ ]{1,40}:\s", first) else first
    m = re.match(r"(.+?\.)(\s|$)", first)
    out = (m.group(1) if m else first).strip()
    return (out[:177] + "...") if len(out) > 180 else (out or "(no header comment)")


def names(text: str, path: str) -> list[str]:
    found: list[str] = []
    for ln in text.splitlines():
        if path.endswith(".bpf.c"):
            m = BPF_PROG.match(ln)
            if m:
                found.append(m.group(1))
                continue
            m = re.match(r"^int BPF_PROG\((\w+)", ln)
            if m:
                found[-1:] = [f"{found[-1]} → {m.group(1)}"] if found else [m.group(1)]
            continue
        if path.endswith(".c"):
            m = C_FUNC.match(ln)
        elif path.endswith(".h"):
            m = C_PROTO.match(ln)
        elif path.endswith(".py"):
            m = PY_DEF.match(ln)
        elif path.endswith(".sh"):
            m = SH_FUNC.match(ln)
        else:
            m = None
        if m and m.group(1) not in ("main", "if", "for", "while", "return", "sizeof"):
            found.append(m.group(1))
    if path.endswith(".py"):
        found = [n for n in found if not n.startswith("_")]
    seen: list[str] = []
    for n in found:
        if n not in seen:
            seen.append(n)
    return seen


def render() -> str:
    rows: dict[str, list[str]] = {}
    for f in files():
        text = (ROOT / f).read_text(errors="replace")
        d = f.rsplit("/", 1)[0] if "/" in f else "."
        ns = names(text, f)
        shown = ", ".join(f"`{n}`" for n in ns[:12]) + (f" (+{len(ns) - 12})" if len(ns) > 12 else "")
        rows.setdefault(d, []).append(f"| [`{f.rsplit('/', 1)[-1]}`](../{f}) | {job(text, f)} | {shown} |")
    out = ["# Code map", "",
           "Generated by `tools/codemap.py` (`make codemap`); CI fails if it is stale. One row per source file:",
           "its job (the file's first comment) and its public names (BPF: section → program). Read this before",
           "opening files. Excluded: vendored code, `vmlinux.h`, generated schema files, docs.", ""]
    for d in sorted(rows):
        out += [f"## {d}", "", "| File | Job | Public names |", "|---|---|---|", *rows[d], ""]
    return "\n".join(out)


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("docs/CODEMAP.md is stale: run `make codemap`", file=sys.stderr)
            return 1
        print(f"codemap: current ({len(files())} files)")
        return 0
    OUT.write_text(text)
    print(f"codemap: wrote {OUT.relative_to(ROOT)} ({len(files())} files)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
